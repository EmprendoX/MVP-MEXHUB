export function getGigsByCategory(categoryId: string): Gig[] {
  return gigsMock.filter((gig) => gig.categoryId === categoryId);
}

export function getTopGigs(limit = 6): Gig[] {
  return [...gigsMock]
    .sort((a, b) => b.rating * Math.log(b.reviewsCount + 1) - a.rating * Math.log(a.reviewsCount + 1))
    .slice(0, limit);
}

export function getGigBySlug(slug: string): Gig | undefined {
  return gigsMock.find((g) => g.slug === slug);
}

export function getSellerById(id: string): SellerProfile | undefined {
  for (const gig of gigsMock) {
    if (gig.seller.id === id) return gig.seller;
  }
  return undefined;
}

export function getGigsBySellerId(sellerId: string): Gig[] {
  return gigsMock.filter((g) => g.seller.id === sellerId);
}

